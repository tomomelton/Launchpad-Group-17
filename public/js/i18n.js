  function getLanguage() {
    return localStorage.getItem('preferredLanguageCode') || localStorage.getItem('preferredLanguage') || 'en';
  }

  function normaliseLanguage(lang) {
    var value = String(lang || 'en').toLowerCase();
    if (value.indexOf('fr') === 0 || value === 'français') return 'fr';
    if (value.indexOf('es') === 0 || value === 'español') return 'es';
    if (value.indexOf('pl') === 0 || value === 'polski') return 'pl';
    if (value.indexOf('ro') === 0 || value === 'română') return 'ro';
    return 'en';
  }

  function t(key) {
    var code = normaliseLanguage(getLanguage());
    return (translations[code] && translations[code][key]) || translations.en[key] || key;
  }

  function applyTranslations() {
    var code = normaliseLanguage(getLanguage());
    document.documentElement.lang = code;

    document.querySelectorAll('[data-i18n]').forEach(function (element) {
      element.textContent = t(element.getAttribute('data-i18n'));
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (element) {
      element.setAttribute('placeholder', t(element.getAttribute('data-i18n-placeholder')));
    });

    document.querySelectorAll('[data-i18n-aria]').forEach(function (element) {
      element.setAttribute('aria-label', t(element.getAttribute('data-i18n-aria')));
    });

    var label = document.querySelector('[data-language-label]');
    if (label) label.textContent = languageNames[code] || languageNames.en;

    document.dispatchEvent(new CustomEvent('languagechange', { detail: { language: code } }));
  }

  window.I18N = {
    t: t,
    apply: applyTranslations,
    languageNames: languageNames,
    normaliseLanguage: normaliseLanguage
  };

  window.setLanguage = function (lang) {
    var code = normaliseLanguage(lang);
    localStorage.setItem('preferredLanguageCode', code);
    localStorage.setItem('preferredLanguage', code);
    var menu = document.querySelector('.lang-menu');
    if (menu) menu.classList.remove('open');
    applyTranslations();
  };

  document.addEventListener('DOMContentLoaded', applyTranslations);
